import { Router } from 'express';
import { z } from 'zod';
import { addProductImage, adminAccounts, adminCustomerWallet, adminCustomers, adminOrders, adjustCustomerWallet, createAdminAccount, createCategory, createProduct, dashboard, deleteCategory, deleteProduct, removeProductImage, updateCategory, updateProduct } from '../controllers/admin.controller.js';
import { handleAdminDispatchEscrow, handleAdminListEscrows, handleAdminRespondToDispute, handleAdminResolveDispute } from '../controllers/escrow.controller.js';
import { updateOrderStatus } from '../controllers/order.controller.js';
import { requireAdmin, requireAdminOperator, requireAuth, requireSuperAdmin } from '../middleware/auth.js';
import { uploadProductImage } from '../middleware/imageUpload.js';
import { uploadEscrowEvidence } from '../middleware/escrowEvidenceUpload.js';
import { validateBody } from '../middleware/validate.js';
import { asyncHandler } from '../utils/http.js';
import { adminAccountSchema, escrowAdminResponseSchema, escrowResolveSchema, orderStatusSchema, productSchema, walletAdjustmentSchema } from '../validators/schemas.js';

const categorySchema = z.object({ slug: z.string().trim().min(2).regex(/^[a-z0-9-]+$/), nameEn: z.string().trim().min(2), nameKm: z.string().trim().min(2), descriptionEn: z.string().optional(), descriptionKm: z.string().optional(), imageUrl: z.string().url().optional(), sortOrder: z.number().int().optional() });
const router = Router();
router.use(requireAuth, requireAdmin);
router.get('/dashboard', asyncHandler(dashboard));
router.get('/accounts', requireSuperAdmin, asyncHandler(adminAccounts));
router.post('/accounts', requireSuperAdmin, validateBody(adminAccountSchema), asyncHandler(createAdminAccount));
router.get('/orders', asyncHandler(adminOrders));
router.patch('/orders/:id/status', validateBody(orderStatusSchema), asyncHandler(updateOrderStatus));
router.get('/escrows', asyncHandler(handleAdminListEscrows));
router.post('/escrows/:orderNumber/dispatch', asyncHandler(handleAdminDispatchEscrow));
router.post('/escrows/:orderNumber/respond', requireAdminOperator, uploadEscrowEvidence, validateBody(escrowAdminResponseSchema), asyncHandler(handleAdminRespondToDispute));
router.post('/escrows/:orderNumber/resolve', requireSuperAdmin, uploadEscrowEvidence, validateBody(escrowResolveSchema), asyncHandler(handleAdminResolveDispute));
router.get('/customers', asyncHandler(adminCustomers));
router.get('/customers/:id/wallet', asyncHandler(adminCustomerWallet));
router.post('/customers/:id/wallet-adjustments', validateBody(walletAdjustmentSchema), asyncHandler(adjustCustomerWallet));
router.post('/products', validateBody(productSchema), asyncHandler(createProduct));
router.put('/products/:id', validateBody(productSchema), asyncHandler(updateProduct));
router.delete('/products/:id', asyncHandler(deleteProduct));
router.post('/categories', validateBody(categorySchema), asyncHandler(createCategory));
router.put('/categories/:id', validateBody(categorySchema), asyncHandler(updateCategory));
router.delete('/categories/:id', asyncHandler(deleteCategory));
router.post('/products/:id/images', uploadProductImage, asyncHandler(addProductImage));
router.delete('/products/:id/images/:imageId', asyncHandler(removeProductImage));
export default router;